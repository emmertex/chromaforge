#!/usr/bin/env python3
"""Convert dcraw's `adobe_coeff` colour-matrix table into camera database entries.

Usage: dcraw_adobe_coeff.py DCRAW_C [--list-makes] > crates/camdb/data/cameras/dcraw.toml

dcraw.c (Dave Coffin, 1997-2018) says "No license is required to download and use dcraw.c" and that only its
Foveon functions are RESTRICTED; "All other code remains free for all uses". `adobe_coeff` is not one of them. Its
rows are XYZ (D65) -> camera matrices x 10000; most were read from Adobe DNG Converter, the rows marked DJC were
measured by Dave Coffin. Only 3 x 3 matrices are taken (four-colour rows and level-only rows are skipped), and only
the matrices: the black / maximum levels are dcraw's own decoders' and stay out. dcraw matches by name prefix; the
database matches exact models, so generic prefixes ("Sony NEX") simply match nothing.

Maintainer decision 2026-10-26: ship this table as a lower-priority camdb source (`dcraw`), below measured data and
the spectral-sensitivity matrices, used only when nothing better exists.
"""
import hashlib
import re
import sys

TWO_WORD_MAKES = ("Phase One", "Konica Minolta")
# Exif makes that differ from dcraw's brand word: (dcraw brand, Exif make, model prefix to add)
EXTRA_MAKES = {
    "Pentax": [("RICOH IMAGING COMPANY, LTD.", "PENTAX ")],
    "Minolta": [("KONICA MINOLTA", "")],
    "Kodak": [("EASTMAN KODAK COMPANY", "")],
}

ROW = re.compile(r'\{\s*"([^"]+)"\s*,\s*([-\w]+)\s*,\s*([-\w]+)\s*,\s*(/\*.*?\*/)?\s*\{([^}]*)\}\s*\}', re.S)


def table(src: str) -> str:
    start = src.index("void CLASS adobe_coeff")
    body = src[start:]
    return body[: body.index("};")]


def split(name: str):
    for m in TWO_WORD_MAKES:
        if name.startswith(m + " "):
            return m, name[len(m) + 1 :]
    make, _, model = name.partition(" ")
    return make, model


def toml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__, file=sys.stderr)
        return 2
    raw = open(sys.argv[1], "rb").read()
    src = raw.decode("latin-1")
    rev = re.search(r"\$Revision: ([\d.]+) \$", src)
    ver = re.search(r'#define DCRAW_VERSION "([^"]+)"', src)
    rows = ROW.findall(table(src))
    if "--list-makes" in sys.argv:
        for m in sorted({split(r[0])[0] for r in rows}):
            print(m)
        return 0
    out = [
        "# Generated by tools/dcraw_adobe_coeff.py from dcraw.c "
        f"{ver.group(1) if ver else '?'} (Revision {rev.group(1) if rev else '?'}, sha256 {hashlib.sha256(raw).hexdigest()}).",
        "# Do not edit by hand: re-run the tool. Source: dcraw's adobe_coeff table (free for all uses; see the tool).",
        "# XYZ (D65) -> camera matrices; lower priority than measured entries and the spectral matrices (Source::Dcraw).",
        "",
    ]
    seen = set()
    kept = skipped = 0
    for name, _black, _maximum, comment, values in rows:
        nums = [int(v) for v in re.findall(r"-?\d+", values)]
        if len(nums) < 9 or nums[0] == 0 or any(nums[9:12]):
            skipped += 1
            continue
        make, model = split(name.strip())
        if not model:
            skipped += 1
            continue
        djc = comment is not None and "DJC" in comment
        m = [[nums[r * 3 + c] / 10000.0 for c in range(3)] for r in range(3)]
        detail = (
            "dcraw adobe_coeff (measured by Dave Coffin)" if djc else "dcraw adobe_coeff (matrix from Adobe DNG Converter)"
        ) + f", dcraw {ver.group(1) if ver else '?'}"
        variants = [(make, model)] + [(exif, prefix + model) for exif, prefix in EXTRA_MAKES.get(make, [])]
        for mk, md in variants:
            key = (mk.split()[0].upper(), md.upper())
            if key in seen:
                continue
            seen.add(key)
            rows_txt = ", ".join("[" + ", ".join(f"{v:.4f}" for v in r) + "]" for r in m)
            out += [
                "[[camera]]",
                f"make = {toml_str(mk)}",
                f"model = {toml_str(md)}",
                "illuminants = [21, 0]",
                f"color_matrix_1 = [{rows_txt}]",
                f"provenance = {{ source = \"dcraw\", detail = {toml_str(detail)} }}",
                "",
            ]
            kept += 1
    sys.stdout.write("\n".join(out))
    print(f"dcraw_adobe_coeff: {kept} entries written, {skipped} rows skipped", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
